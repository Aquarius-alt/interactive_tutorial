#pragma once
#include <SDL3/SDL.h>
#include <string>

// Экран "Ранги": открывается кнопкой "получить ранг" в профиле.
//   BACK (или Esc) - назад в профиль.
//   IMPORT - открывает папку заданий на ранг (<Documents>\myproject\<логин>\_ranks, создаётся сама);
//            задание - в формате теста из репозитория.
//   карточка "+" (создать задание) - закрыта паролем: сначала окно ввода пароля, при верном пароле
//            открывается окно создания теста (то же, что "+" на вкладке TESTS экрана CREATE).
//            Кнопка ADD сохраняет задание в <Documents>\myproject\<логин>\_ranks\<название>\ (формат теста),
//            и оно появляется карточкой рядом с "+" (название, звание, теги предмета).
//            Cancel / Esc закрывают окно без сохранения.
//   клик по карточке задания - прохождение: вопросы по одному, ответы вводятся в поле (PREV / NEXT / FINISH).
//            Если верны все ответы, в ранги профиля добавляется запись "теги - звание" (один раз на задание);
//            иначе показывается счёт и можно попробовать ещё раз.
// Пока открыто окно пароля или окно теста, все события должны идти только этому экрану.

enum class RanksResult { None, Back };

void        Ranks_Open(SDL_Window* window, const std::string& login);
void        Ranks_Poll();                       // каждый кадр: вложения, выбранные в окне теста
bool        Ranks_IsModalOpen();                // открыто окно пароля или окно теста
void        Ranks_Draw(SDL_Renderer* r, int w, int h, SDL_Rect* nd, int& ndCount);
RanksResult Ranks_Handle(const SDL_Event& e);   // Back = кнопка BACK или Esc
void        Ranks_Destroy();                    // до SDL_DestroyRenderer
